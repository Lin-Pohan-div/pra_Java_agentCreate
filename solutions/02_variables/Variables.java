public class Variables {

    public static int sum(int a, int b) {
        int result = a + b;
        return result;
    }

    public static double average(int a, int b) {
        return (a + b) / 2.0;
    }

    public static String describe(int n) {
        int label = n;
        return "n=" + label;
    }
}
